it('calculates the equinox days', function (int $year, string $vernalEquinoxDay, string $autumnalEquinoxDay) {
    $holidays = Holidays::for(country: 'jp', year: $year)->get();

    expect(findDate($holidays, '春分の日')?->format('m-d'))->toBe($vernalEquinoxDay);
    expect(findDate($holidays, '秋分の日')?->format('m-d'))->toBe($autumnalEquinoxDay);
})->with([
    [2015, '03-21', '09-23'],
    [2016, '03-20', '09-22'],
    [2020, '03-20', '09-22'],
    [2024, '03-20', '09-22'],
    [2027, '03-21', '09-23'],
]);

it('adds a substitute holiday when a holiday falls on a sunday', function () {
    // Constitution Day 2026 is on Sunday 3 May, and 4 and 5 May are holidays as well.
    $holidays = Holidays::for(country: 'jp', year: 2026)->get();

    expect(findDate($holidays, '振替休日')?->format('Y-m-d'))->toBe('2026-05-06');
    expect($holidays)->toContainElement(
        fn (Holiday $holiday): bool => $holiday->name === '振替休日' && $holiday->type === HolidayType::Observed,
    );

    // The Emperor's Birthday 2025 is on Sunday 23 February.
    $holidays = Holidays::for(country: 'jp', year: 2025)->get();

    expect(findDate($holidays, '振替休日')?->format('Y-m-d'))->toBe('2025-02-24');
});

it('adds a holiday for a day between two holidays', function () {
    // Respect for the Aged Day and Autumnal Equinox Day 2026 are on 21 and 23 September.
    $holidays = Holidays::for(country: 'jp', year: 2026)->get();

    expect(findDate($holidays, '国民の休日')?->format('Y-m-d'))->toBe('2026-09-22');
});

it('follows the emperor\'s birthday of the time', function () {
    expect(findDate(Holidays::for(country: 'jp', year: 2018)->get(), '天皇誕生日')?->format('Y-m-d'))->toBe('2018-12-23');
    expect(findDate(Holidays::for(country: 'jp', year: 2019)->get(), '天皇誕生日'))->toBeNull();
    expect(findDate(Holidays::for(country: 'jp', year: 2020)->get(), '天皇誕生日')?->format('Y-m-d'))->toBe('2020-02-23');
});

it('has the extra holidays of 2019', function () {
    $holidays = Holidays::for(country: 'jp', year: 2019)->get();

    expect(findDate($holidays, '天皇の即位の日')?->format('Y-m-d'))->toBe('2019-05-01');
    expect(findDate($holidays, '即位礼正殿の儀の行われる日')?->format('Y-m-d'))->toBe('2019-10-22');

    // 30 April and 2 May are between two holidays, and 6 May replaces Children's Day on a Sunday.
    $days = array_map(
        fn (Holiday $holiday): string => $holiday->date->format('Y-m-d'),
        array_filter($holidays, fn (Holiday $holiday): bool => $holiday->type === HolidayType::Observed),
    );

    expect(array_values($days))->toContain('2019-04-30', '2019-05-02', '2019-05-06');
});

it('moves marine day, sports day and mountain day for the olympic games', function () {
    $holidays = Holidays::for(country: 'jp', year: 2020)->get();

    expect(findDate($holidays, '海の日')?->format('Y-m-d'))->toBe('2020-07-23');
    expect(findDate($holidays, 'スポーツの日')?->format('Y-m-d'))->toBe('2020-07-24');
    expect(findDate($holidays, '山の日')?->format('Y-m-d'))->toBe('2020-08-10');

    $holidays = Holidays::for(country: 'jp', year: 2021)->get();

    expect(findDate($holidays, '海の日')?->format('Y-m-d'))->toBe('2021-07-22');
    expect(findDate($holidays, 'スポーツの日')?->format('Y-m-d'))->toBe('2021-07-23');
    expect(findDate($holidays, '山の日')?->format('Y-m-d'))->toBe('2021-08-08');
    expect(findDate($holidays, '振替休日')?->format('Y-m-d'))->toBe('2021-08-09');
});

it('uses the name that sports day had at the time', function () {
    expect(findDate(Holidays::for(country: 'jp', year: 2019)->get(), '体育の日')?->format('Y-m-d'))->toBe('2019-10-14');
    expect(findDate(Holidays::for(country: 'jp', year: 2022)->get(), 'スポーツの日')?->format('Y-m-d'))->toBe('2022-10-10');
});

it('has no mountain day before it was created', function () {
    expect(findDate(Holidays::for(country: 'jp', year: 2015)->get(), '山の日'))->toBeNull();
    expect(findDate(Holidays::for(country: 'jp', year: 2016)->get(), '山の日')?->format('Y-m-d'))->toBe('2016-08-11');
});
